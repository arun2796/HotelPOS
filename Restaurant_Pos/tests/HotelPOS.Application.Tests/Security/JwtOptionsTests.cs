using FluentAssertions;
using HotelPOS.Application.Common;
using Xunit;

namespace HotelPOS.Application.Tests.Security;

// The signing key rule behind Jwt:SigningKey validation at start-up (ApiServiceRegistration). A key that is long
// enough but publicly known must be refused: the template placeholder and the committed development key.
public class JwtOptionsTests
{
    private const string TemplatePlaceholder = "<generated by installer: 64 random characters>";
    private const string DevelopmentKey = "DEVELOPMENT-ONLY-signing-key-never-use-in-production-7c4f9a2e";
    private const string GeneratedKey = "Z2VuZXJhdGVkLWJ5LWluc3RhbGxlci00OC1yYW5kb20tYnl0ZXMtYmFzZTY0";

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("   ")]
    [InlineData("too-short-key")]
    public void MissingOrShortKeys_AreRefused(string? key) =>
        JwtOptions.SigningKeyProblem(key, isDevelopment: false).Should().Contain("at least 32 characters");

    [Fact]
    public void TheTemplatePlaceholder_IsRefused_EvenThoughItIsLongEnough()
    {
        TemplatePlaceholder.Length.Should().BeGreaterThanOrEqualTo(JwtOptions.MinimumSigningKeyLength, "that is why the length rule alone did not catch it");

        JwtOptions.SigningKeyProblem(TemplatePlaceholder, isDevelopment: false).Should().Contain("template placeholder");
        JwtOptions.SigningKeyProblem(TemplatePlaceholder, isDevelopment: true).Should().Contain("template placeholder");
    }

    [Fact]
    public void TheCommittedDevelopmentKey_IsRefused_OutsideDevelopment()
    {
        JwtOptions.SigningKeyProblem(DevelopmentKey, isDevelopment: false).Should().Contain("development key");
        JwtOptions.SigningKeyProblem(DevelopmentKey, isDevelopment: true).Should().BeNull();
    }

    [Fact]
    public void AGeneratedKey_IsAccepted() =>
        JwtOptions.SigningKeyProblem(GeneratedKey, isDevelopment: false).Should().BeNull();
}
